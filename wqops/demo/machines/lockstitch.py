def _swap(node, old, new):
    code, name, qty, src, unit, kids = node
    return (code, name, qty, src, unit, [new if k[0] == old[0] else _swap(k, old, new) for k in kids])


def _find(node, code):
    if node[0] == code:
        return node
    return next((x for k in node[5] if (x := _find(k, code))), None)


