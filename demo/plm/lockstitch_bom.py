def rows(node=TREE, level=1):
    code, name, qty, src, unit, kids = node
    yield [level, code, name, qty, unit, src]
    for k in kids:
        yield from rows(k, level + 1)


def write(path: Path) -> dict:
    import openpyxl  # noqa: PLC0415 - FreeCAD reads this file without openpyxl
    from openpyxl.styles import Font  # noqa: PLC0415

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "BOM"
    ws.append(["层级", "编码", "名称", "数量", "单位", "自制/外购"])
    for c in ws[1]:
        c.font = Font(bold=True)
    all_rows = list(rows())
    for r in all_rows:
        ws.append(r)
    for col, w in zip("ABCDEF", (6, 18, 34, 7, 6, 9), strict=True):
        ws.column_dimensions[col].width = w
    wb.save(path)
    codes = {r[1] for r in all_rows}
    return {"rows": len(all_rows), "parts": len(codes),
            "assemblies": sum(1 for r, nxt in zip(all_rows, [*all_rows[1:], [0]], strict=True) if nxt[0] > r[0])}


