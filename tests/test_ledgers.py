def test_model_proposal_is_checked_and_logged(world):
    reply = {"stop_reason": "tool_use", "usage": {"input_tokens": 1200, "output_tokens": 300}, "content": [{
        "type": "tool_use", "id": "t1", "name": "propose_mapping", "input": {
            "target": "ncr", "confidence": "high", "notes": "A nonconformance log.",
            "mapping": [{"field": "external_no", "column": "NCR #"}, {"field": "description", "column": "Description"},
                        {"field": "disposition", "column": "Disposition"}, {"field": "status", "column": "Status"},
                        {"field": "closed_on", "column": "Closed"}, {"field": "owner", "column": "Inspector"}],
            "values": [{"field": "disposition", "ledger_value": "RTV", "our_value": "return_to_supplier"},
                       {"field": "disposition", "ledger_value": "Scrap", "our_value": "scrap"},
                       {"field": "status", "ledger_value": "Closed", "our_value": "closed"},
                       {"field": "status", "ledger_value": "Cancelled - entered twice", "our_value": "cancelled"},
                       {"field": "status", "ledger_value": "Open", "our_value": "reopened"}]}}]}
    s = Scripted(reply)
    _, imp = start(world, "NCR log", model=s.model())
    body = s.requests[0]["body"]
    assert body["tool_choice"]["name"] == "propose_mapping" and "Values in 'Disposition'" in \
        body["messages"][0]["content"]
    assert imp["engine"] == "ai" and imp["confidence"] == "medium"          # something did not fit
    assert "owner" not in imp["mapping"] and imp["values_map"]["status"] == {"Closed": "closed",
                                                                              "Cancelled - entered twice": "cancelled"}
    assert "Not used" in imp["notes"]
    run = world.execute("select * from ai_runs where id = %s", (imp["ai_run"],)).fetchone()
    assert run["kind"] == "ledger" and run["usage"]["input_tokens"] == 1200
    LS.run_import(world, Acc.get(world, JORDAN), imp["id"], PW)
    rows = {r["external_no"]: r for r in world.execute("select * from ncr_records")}
    assert rows["NCR-2026-01"]["disposition"] == "return_to_supplier" and rows["NCR-2026-03"]["status"] == "cancelled"
    s2 = Scripted({"stop_reason": "end_turn", "content": [{"type": "text", "text": "no"}]})
    _, imp2 = start(world, "CAPA log", model=s2.model())
    assert imp2["engine"] == "rules" and imp2["target"] == "capa" and "could not propose" in imp2["notes"]


