def test_ledgers_api(db_url):
    c = TestClient(create_app({}, lambda: (DEMO, "ok"), db_url=db_url, ai=L.Anthropic("", env={})))
    c.__enter__()
    with DB.connect(db_url) as conn:
        for e in (JORDAN, PAT, "alex@demo.example"):
            Acc.set_password(conn, e, PW)
        _, (doc, pdf) = imported(conn, ["NCR log", "QP-05"])

    def login(e):
        assert c.post("/api/login", json={"email": e, "password": PW}).status_code == 200

    login("alex@demo.example")
    assert c.post("/api/ledgers", json={"document_id": doc["id"]}).status_code == 403
    login(PAT)                                              # purchasing: supplier lists only
    assert c.get(f"/api/ledgers?document_id={doc['id']}").json()["kinds"] == {"supplier": "Supplier list"}
    assert c.post("/api/ledgers", json={"document_id": doc["id"], "target": "ncr"}).status_code == 403
    login(JORDAN)
    r = c.post("/api/ledgers", json={"document_id": doc["id"]})
    assert r.status_code == 201
    v = r.json()
    assert v["target"] == "ncr" and v["preview"]["total"] == 7 and v["preview"]["fields"]["severity"]["choices"] == \
        ["minor", "major"]
    assert v["preview"]["choice_values"]["disposition"] == ["RTV", "Return to supplier", "Scrap", "Use as is"]
    put = c.put(f"/api/ledgers/{v['id']}", json={"mapping": v["mapping"], "values": v["values_map"],
                                                 "header_row": 2})
    assert put.json()["engine"] == "person"
    assert c.post(f"/api/ledgers/{v['id']}/import", json={"password": "bad pass 1"}).status_code == 403
    out = c.post(f"/api/ledgers/{v['id']}/import", json={"password": PW}).json()
    assert out["status"] == "imported" and len(out["outcomes"]) == 7 and out["signatures"][0]["email"] == JORDAN
    assert c.post(f"/api/ledgers/{v['id']}/import", json={"password": PW}).status_code == 409
    ncrs = c.get("/api/quality/ncrs?status=all").json()
    assert len(ncrs) == 7 and {n["external_no"] for n in ncrs} >= {"NCR-2025-01"}
    r = c.post("/api/ledgers", json={"document_id": pdf["id"]})
    assert r.status_code == 409 and "Excel" in r.json()["detail"]


def test_odd_spreadsheets_from_the_review():
    """Cases an independent review found: none may write a guessed value or fail with an error page."""
    assert LG.parse_number("12,5") is None and LG.parse_number("1,200") == 1200 and LG.parse_number("3 pcs") == 3
    assert LG.parse_date("03/04/2024") is None                              # March 4 or 3 April: unknown
    assert LG.parse_date("13/04/2024").isoformat() == "2024-04-13" and LG.parse_date("4/4/2024").month == 4
    t = LG.table("x.csv", "描述,数量\n螺栓弯曲,3\n".encode("gb18030"))
    assert t.headers == ["描述", "数量"]
    t = LG.table("x.csv", "Description,Qty\nbent,0\n".encode("utf-16"))
    assert t.data()[0][1] == {"Description": "bent", "Qty": "0"}
    r = LG.rows(t, targets()["ncr"], {"description": {"column": "Description"}, "quantity": {"column": "Qty"}}, {})
    assert "quantity" not in r[0]["values"] and "above 0" in r[0]["problems"][0]
    t = LG.table("x.csv", b"A,A,A (2),,\n1,2,3,,\n")
    assert t.headers[:3] == ["A", "A (2)", "A (2) (2)"] and len(set(h for h in t.headers if h)) == 3
    assert LG.table("x.csv", b"Desc,X\n\x00bent,#N/A\n").data()[0][1]["Desc"] == "bent"


def test_sheets_unknowns_copies_and_links(world):
    wb = openpyxl.Workbook()
    for name in ("NCR 2023", "NCR 2024"):
        ws = wb.create_sheet(name)
        ws.append(["NCR #", "Date", "Description", "Class", "Status"])
        ws.append(["001", f"{name[-4:]}-03-01", f"Problem of {name}", "Class A", "Closed - verified"])
    wb.remove(wb["Sheet"])
    buf = io.BytesIO()
    wb.save(buf)
    imp = LIB.new_import(world, JORDAN, "t")
    doc = LIB.add_file(world, imp["id"], "logs/two sheets.xlsx", buf.getvalue())
    copy = LIB.add_file(world, imp["id"], "logs/copy of two sheets.xlsx", buf.getvalue())
    LIB.extract_import(world, imp["id"])
    with pytest.raises(LS.LedgerError, match="same as document"):
        LS.table_of(world, LIB.get(world, copy["id"]))
    for sheet in ("NCR 2023", "NCR 2024"):
        t = LS.table_of(world, doc, sheet)
        p = LG.rules_mapping("ncr", t, LS.flds(world, "ncr"))
        li = LS.create(world, JORDAN, doc, "ncr", t, p, "rules")
        assert LS.preview(world, li)["already"] == 0                       # the other sheet's rows are not these
        assert LS.run_import(world, Acc.get(world, JORDAN), li["id"], PW)["result"]["imported"] == 1
    rows = world.execute("select * from ncr_records order by id").fetchall()
    assert [r["external_no"] for r in rows] == ["001", "001"]                # same number, different years
    assert all(r["severity"] is None and r["status"] == "open" for r in rows)  # "Class A", "Closed - verified"
    assert "Severity in the ledger: 'Class A', not matched; set it before closing" in rows[0]["description"]
    n = rows[0]
    world.execute("update ncr_records set status = 'dispositioned' where id = %s", (n["id"],))
    with pytest.raises(Q.QualityError, match="no severity"):
        Q.close_ncr(world, n["id"], Acc.get(world, JORDAN), PW)
    csv_ = LIB.add_file(world, imp["id"], "capa.csv", b"CAR No.,Type,Problem,NCR Ref\nC-1,Corrective,x,001\n")
    LIB.extract_import(world, imp["id"])
    t = LS.table_of(world, LIB.get(world, csv_["id"]))
    li = LS.create(world, JORDAN, LIB.get(world, csv_["id"]), "capa", t,
                   LG.rules_mapping("capa", t, LS.flds(world, "capa")), "rules")
    LS.run_import(world, Acc.get(world, JORDAN), li["id"], PW)
    capa = world.execute("select * from capas").fetchone()
    assert not world.execute("select 1 from capa_ncrs").fetchone()          # two NCRs are 001: no guessed link
    assert "more than one NCR has that number" in capa["description"]
    assert "Status not given in the ledger; starts as a draft" in capa["description"]
