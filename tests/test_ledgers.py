def start(conn, part, target=None, model=None, by=JORDAN):
    _, (doc,) = imported(conn, [part])
    t = LS.table_of(conn, doc)
    tg = {k: LS.flds(conn, k) for k in LG.TARGETS}
    p = LAI.propose(conn, {"email": by, "roles": ["quality"]}, t, tg, model, target=target or "", today=AS_OF)
    return doc, LS.create(conn, by, doc, p["target"], t, p["proposal"], p["engine"], p["ai_run"])


def test_ncr_log_import_is_signed_and_happens_once(world):
    doc, imp = start(world, "NCR log")
    assert imp["target"] == "ncr" and imp["engine"] == "rules"
    pv = LS.preview(world, imp)
    assert (pv["total"], pv["ready"], pv["with_problems"]) == (7, 7, 2)
    with pytest.raises(Q.SignatureError):
        LS.run_import(world, Acc.get(world, JORDAN), imp["id"], "wrong pass 1")
    assert world.execute("select count(*) as n from auth_events where event = 'signature_failed'").fetchone()["n"] == 1
    out = LS.run_import(world, Acc.get(world, JORDAN), imp["id"], PW)
    assert out["status"] == "imported" and out["result"] == {"imported": 7, "drafted": 0, "skipped": 0}
    ncrs = {r["external_no"]: r for r in world.execute("select * from ncr_records order by id")}
    first = ncrs["NCR-2025-01"]
    assert (first["status"], first["severity"], first["disposition"], str(first["reported_on"])) == \
        ("closed", "minor", "return_to_supplier", "2025-02-11")
    assert first["closed_at"].date().isoformat() == "2025-02-20" and first["source_row"] == 3
    assert ncrs["NCR-2025-04"]["severity"] == "major"
    assert ncrs["NCR-2026-01"]["disposition"] is None                       # "RTV": unknown, not guessed
    odd = ncrs["NCR-2026-03"]
    assert odd["status"] == "open" and \
        "Status in the ledger: 'Cancelled - entered twice', not matched; imported as open" in odd["description"]
    assert odd["title"] == "Stretch wrap roll damaged in warehouse"
    assert [h["action"] for h in Q.history(world, "ncr", first["id"])] == ["imported", "closed before WenQuest Ops"]
    assert [s["meaning"] for s in Q.signatures(world, "ledger", imp["id"])] == ["Ledger rows imported"]
    with pytest.raises(LS.LedgerError, match="already imported"):
        LS.run_import(world, Acc.get(world, JORDAN), imp["id"], PW)
    again = LS.create(world, SAM, doc, "ncr", LS.table_of(world, doc), {"mapping": imp["mapping"],
                                                                        "values": imp["values_map"]}, "person")
    assert LS.preview(world, again)["already"] == 7
    res = LS.run_import(world, Acc.get(world, SAM), again["id"], PW)
    assert res["result"] == {"imported": 0, "drafted": 0, "skipped": 7}
    assert world.execute("select count(*) as n from ncr_records").fetchone()["n"] == 7
    with pytest.raises(Exception, match="append-only"):
        world.execute("delete from ledger_rows")


