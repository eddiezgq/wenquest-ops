def test_rows_keep_unknowns_unknown():
    t = tab("NCR log")
    m = LG.rules_mapping("ncr", t, targets()["ncr"])
    rows = {r["row"]: r for r in LG.rows(t, targets()["ncr"], m["mapping"], m["values"])}
    first = rows[3]
    assert first["ok"] and first["values"] == {
        "external_no": "NCR-2025-01", "reported_on": "2025-02-11", "item_code": "HX-BOLT-M8",
        "supplier": "Gulf Fasteners (Demo)", "quantity": 200.0, "description": "Thread damage on 14 bolts in box 3",
        "severity": "minor", "disposition": "return_to_supplier", "status": "closed", "closed_on": "2025-02-20"}
    rtv = rows[7]
    assert "disposition" not in rtv["values"] and rtv["values"]["closed_on"] == "2026-01-30"
    assert rtv["problems"] == ["Disposition: 'RTV' is not matched to one of ours, left unknown"] and rtv["ok"]
    assert "status" not in rows[9]["values"]                                        # "Cancelled - entered twice"
    bad = LG.table("x.csv", b"Description,Date,Qty\n,2025-01-01,3\nbent,someday,many\n")
    r1, r2 = LG.rows(bad, targets()["ncr"], {"description": {"column": "Description"},
                                             "reported_on": {"column": "Date"}, "quantity": {"column": "Qty"}}, {})
    assert not r1["ok"] and r1["problems"] == ["missing Description"]
    assert r2["ok"] and set(r2["problems"]) == {"Date reported: 'someday' is not a date that can be read one way only",
                                                "Quantity: 'many' is not a quantity above 0"}


