def zipped(parts) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for p in parts:
            name, data = file(p)
            z.writestr(name.split("/", 1)[1], data)
        z.writestr("__MACOSX/._junk", b"x")
        z.writestr("notes/setup.exe", b"MZ")
    return buf.getvalue()


