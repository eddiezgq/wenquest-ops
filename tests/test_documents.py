def test_quotes_are_checked_against_the_file():
    text = "Doc No.: QP-08 Rev: C Effective date: 2025-06-02\nControl of Nonconforming Product\nOwner: Quality Manager"
    p = {"doc_type": "procedure", "process": "nonconformance", "number": "QP-08", "title": "Control of Nonconforming "
         "Product", "revision": "C", "effective_date": "2025-06-02", "owner": "Quality Manager", "confidence": "high",
         "refs": ["QP-08", "F-QA-999"],
         "evidence": {"doc_type": {"quote": "Control of Nonconforming Product"},
                      "process": {"quote": "control of   nonconforming product"},       # spacing and case ignored
                      "number": {"quote": "Doc No.: QP-08"}, "title": {"quote": "Control of Nonconforming Product"},
                      "revision": {"quote": "Rev: C"}, "effective_date": {"quote": "Effective date: 2025-06-02"},
                      "owner": {"quote": "Owner: Quality Manager"}}}
    v = K.verify(p, "QP-08.pdf", "Procedures", text)
    assert all(e["verified"] for e in v["evidence"].values()) and v["confidence"] == "high" and K.batch_ok(v)
    assert v["refs"] == ["QP-08"] and v["refs_unverified"] == ["F-QA-999"]          # a named form must be in the file
    p2 = json.loads(json.dumps(p))
    p2["evidence"]["title"]["quote"] = "Control of Nonconforming Material"           # not in the file
    p2["evidence"]["revision"]["quote"] = "Doc No.: QP-08"                           # in the file, but no C in it
    p2["effective_date"] = "2025-07-02"                                              # quote has another date
    v2 = K.verify(p2, "QP-08.pdf", "Procedures", text)
    assert {f for f, e in v2["evidence"].items() if not e["verified"]} == {"title", "revision", "effective_date"}
    assert v2["confidence"] == "medium" and not K.batch_ok(v2)                       # high needs verified core fields
    p3 = dict(p, evidence={})
    assert not any(e["verified"] for e in K.verify(p3, "x", "", text)["evidence"].values())
    assert K.dates_in("on March 3, 2025 and 3 Mar 2025, 03/03/2025, 2025-03-03") == [K.dt.date(2025, 3, 3)] * 4


