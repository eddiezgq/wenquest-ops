def classified(doc_type, process, title, quote_title, number=None, conf="high", refs=()):
    inp = {"doc_type": {"value": doc_type, "quote": quote_title}, "process": {"value": process, "quote": quote_title},
           "title": {"value": title, "quote": quote_title}, "confidence": conf, "language": "en",
           "summary": f"{title}.", "refs": list(refs)}
    if number:
        inp["number"] = {"value": number, "quote": f"Doc No.: {number}"}
    return {"stop_reason": "tool_use", "usage": {"input_tokens": 900, "output_tokens": 120},
            "content": [{"type": "tool_use", "id": "t1", "name": "record_classification", "input": inp}]}


